# Обратный карманный словарь: некоторые EN-токены тоже полезно расширять.
EN_HINTS: Dict[str, List[str]] = {
    "pdf": ["documents", "docx"],
    "scraping": ["parser", "parsing"],
    "charts": ["visualization", "plots"],
    "resume": ["cv", "interview"],
    "game": ["gamedev", "games"],
}


def expand(tokens: List[str]) -> List[str]:
    """Добавляет к списку токенов w:... синонимы (без дубликатов)."""
    extra: List[str] = []
    seen = set(tokens)
    for tok in tokens:
        stem = tok[2:] if tok.startswith("w:") else tok
        for syn in SYNONYMS.get(stem, []) + EN_HINTS.get(stem, []):
            key = "w:" + syn
            if key not in seen:
                seen.add(key)
                extra.append(key)
    return tokens + extra
